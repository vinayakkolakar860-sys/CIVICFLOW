package com.civicflow.reporting;

import com.civicflow.exception.ExportException;
import com.lowagie.text.*;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfPageEventHelper;
import com.lowagie.text.pdf.PdfWriter;
import com.lowagie.text.pdf.ColumnText;

import java.awt.Color;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.format.DateTimeFormatter;
import java.util.List;

/**
 * Generates branded, enterprise-formatted PDF reports using OpenPDF with
 * a clear educational simulation watermark and page numbering.
 */
public class PdfReportExporter {

    private static final DateTimeFormatter TS_FMT = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");
    private static final Color BRAND_DARK = new Color(17, 24, 39);
    private static final Color BRAND_PRIMARY = new Color(40, 85, 217);
    private static final Color ALT_ROW = new Color(245, 247, 251);
    private static final Color BORDER_GRAY = new Color(218, 224, 236);
    private static final Color WATERMARK_BG = new Color(254, 243, 199);
    private static final Color WATERMARK_TEXT = new Color(146, 64, 14);

    public Path export(ReportData report, Path targetFile) {
        if (report == null) {
            throw new ExportException("Report payload cannot be null.");
        }
        if (targetFile == null) {
            throw new ExportException("Export file path is required.");
        }

        Path normalized = targetFile.toAbsolutePath().normalize();
        Path parent = normalized.getParent();
        if (parent == null || !Files.exists(parent) || !Files.isDirectory(parent)) {
            throw new ExportException("Selected export directory does not exist: " + parent);
        }
        if (!Files.isWritable(parent)) {
            throw new ExportException("Export directory is not writable.");
        }

        Rectangle pageSize = report.getHeaders().size() > 6 ? PageSize.A4.rotate() : PageSize.A4;
        Document document = new Document(pageSize, 32, 32, 36, 42);

        try (OutputStream out = Files.newOutputStream(normalized)) {
            PdfWriter writer = PdfWriter.getInstance(document, out);
            writer.setPageEvent(new FooterPageEvent(report.getWatermark()));
            document.open();

            // Header Banner
            PdfPTable headerBox = new PdfPTable(1);
            headerBox.setWidthPercentage(100);
            PdfPCell brandCell = new PdfPCell();
            brandCell.setBackgroundColor(BRAND_DARK);
            brandCell.setPadding(14);
            brandCell.setBorder(Rectangle.NO_BORDER);

            Font brandFont = new Font(Font.HELVETICA, 14, Font.BOLD, Color.WHITE);
            Font titleFont = new Font(Font.HELVETICA, 11, Font.NORMAL, new Color(203, 213, 225));
            brandCell.addElement(new Paragraph("CIVICFLOW — Election Management Suite (CEMS)", brandFont));
            brandCell.addElement(new Paragraph(report.getTitle(), titleFont));
            headerBox.addCell(brandCell);
            document.add(headerBox);

            // Simulated Data Watermark Banner
            PdfPTable wmTable = new PdfPTable(1);
            wmTable.setWidthPercentage(100);
            wmTable.setSpacingBefore(6);
            PdfPCell wmCell = new PdfPCell(new Phrase(report.getWatermark(), new Font(Font.HELVETICA, 9, Font.BOLD, WATERMARK_TEXT)));
            wmCell.setBackgroundColor(WATERMARK_BG);
            wmCell.setHorizontalAlignment(Element.ALIGN_CENTER);
            wmCell.setPadding(6);
            wmCell.setBorderColor(new Color(245, 158, 11));
            wmTable.addCell(wmCell);
            document.add(wmTable);

            // Metadata
            Font metaFont = new Font(Font.HELVETICA, 9, Font.NORMAL, new Color(75, 85, 99));
            Paragraph meta = new Paragraph(
                    (report.getSubtitle() != null && !report.getSubtitle().isBlank() ? report.getSubtitle() + "\n" : "")
                            + "Generated At: " + report.getGeneratedAt().format(TS_FMT)
                            + "   |   Generated By: " + report.getGeneratedBy()
                            + "   |   Total Records: " + report.getRows().size(),
                    metaFont);
            meta.setSpacingBefore(8);
            meta.setSpacingAfter(10);
            document.add(meta);

            if (report.getHeaders().isEmpty()) {
                document.add(new Paragraph("No columns configured for this report."));
            } else if (report.getRows().isEmpty()) {
                PdfPTable emptyBox = new PdfPTable(1);
                emptyBox.setWidthPercentage(100);
                PdfPCell emptyCell = new PdfPCell(new Phrase("No records matched the selected report filters.", metaFont));
                emptyCell.setPadding(18);
                emptyCell.setHorizontalAlignment(Element.ALIGN_CENTER);
                emptyCell.setBackgroundColor(ALT_ROW);
                emptyCell.setBorderColor(BORDER_GRAY);
                emptyBox.addCell(emptyCell);
                document.add(emptyBox);
            } else {
                PdfPTable table = new PdfPTable(report.getHeaders().size());
                table.setWidthPercentage(100);
                table.setHeaderRows(1);

                Font thFont = new Font(Font.HELVETICA, 9, Font.BOLD, Color.WHITE);
                for (String header : report.getHeaders()) {
                    PdfPCell cell = new PdfPCell(new Phrase(header != null ? header : "", thFont));
                    cell.setBackgroundColor(BRAND_PRIMARY);
                    cell.setPadding(7);
                    cell.setBorderColor(BRAND_PRIMARY);
                    table.addCell(cell);
                }

                Font tdFont = new Font(Font.HELVETICA, 8.5f, Font.NORMAL, new Color(24, 34, 48));
                int rowIdx = 0;
                for (List<String> row : report.getRows()) {
                    Color bg = (rowIdx % 2 == 1) ? ALT_ROW : Color.WHITE;
                    for (int c = 0; c < report.getHeaders().size(); c++) {
                        String val = c < row.size() && row.get(c) != null ? row.get(c) : "";
                        PdfPCell cell = new PdfPCell(new Phrase(val, tdFont));
                        cell.setBackgroundColor(bg);
                        cell.setPadding(6);
                        cell.setBorderColor(BORDER_GRAY);
                        table.addCell(cell);
                    }
                    rowIdx++;
                }
                document.add(table);
            }

            document.close();
            return normalized;
        } catch (Exception e) {
            if (document.isOpen()) {
                document.close();
            }
            throw new ExportException("Failed to generate PDF report: " + e.getMessage(), e);
        }
    }

    private static class FooterPageEvent extends PdfPageEventHelper {
        private final String watermark;
        private final Font footerFont = new Font(Font.HELVETICA, 8, Font.ITALIC, new Color(105, 117, 134));

        FooterPageEvent(String watermark) {
            this.watermark = watermark;
        }

        @Override
        public void onEndPage(PdfWriter writer, Document document) {
            ColumnText.showTextAligned(
                    writer.getDirectContent(),
                    Element.ALIGN_LEFT,
                    new Phrase("CIVICFLOW CEMS | " + watermark, footerFont),
                    document.left(),
                    document.bottom() - 18,
                    0
            );
            ColumnText.showTextAligned(
                    writer.getDirectContent(),
                    Element.ALIGN_RIGHT,
                    new Phrase("Page " + writer.getPageNumber(), footerFont),
                    document.right(),
                    document.bottom() - 18,
                    0
            );
        }
    }
}
