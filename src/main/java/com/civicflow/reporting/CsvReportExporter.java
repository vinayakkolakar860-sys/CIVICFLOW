package com.civicflow.reporting;

import com.civicflow.exception.ExportException;
import com.civicflow.security.CsvSanitizer;

import java.io.BufferedWriter;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.format.DateTimeFormatter;
import java.util.List;
import java.util.stream.Collectors;

/**
 * Exports ReportData to UTF-8 CSV while neutralizing spreadsheet formula injection.
 */
public class CsvReportExporter {

    private static final DateTimeFormatter TS_FMT = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    public Path export(ReportData report, Path targetFile) {
        if (report == null) {
            throw new ExportException("Report payload cannot be null.");
        }
        if (targetFile == null) {
            throw new ExportException("Export file path is required.");
        }

        Path normalized = targetFile.toAbsolutePath().normalize();
        Path parent = normalized.getParent();
        if (parent == null || !Files.exists(parent) || !Files.isDirectory(parent)) {
            throw new ExportException("Selected export directory does not exist: " + parent);
        }
        if (!Files.isWritable(parent)) {
            throw new ExportException("Export directory is not writable.");
        }

        try (BufferedWriter writer = Files.newBufferedWriter(normalized, StandardCharsets.UTF_8)) {
            // Metadata banner rows (sanitized)
            writer.write(CsvSanitizer.sanitizeCell("CIVICFLOW — Election Management Suite (CEMS)"));
            writer.newLine();
            writer.write(CsvSanitizer.sanitizeCell(report.getTitle()) + "," + CsvSanitizer.sanitizeCell(report.getWatermark()));
            writer.newLine();
            writer.write(CsvSanitizer.sanitizeCell("Generated: " + report.getGeneratedAt().format(TS_FMT))
                    + "," + CsvSanitizer.sanitizeCell("Generated By: " + report.getGeneratedBy()));
            writer.newLine();
            writer.newLine();

            // Column headers
            writer.write(report.getHeaders().stream()
                    .map(CsvSanitizer::sanitizeCell)
                    .collect(Collectors.joining(",")));
            writer.newLine();

            // Data rows
            for (List<String> row : report.getRows()) {
                writer.write(row.stream()
                        .map(CsvSanitizer::sanitizeCell)
                        .collect(Collectors.joining(",")));
                writer.newLine();
            }
            return normalized;
        } catch (IOException e) {
            throw new ExportException("Failed to write CSV export file: " + e.getMessage(), e);
        }
    }
}
